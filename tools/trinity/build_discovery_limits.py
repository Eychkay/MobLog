"""Generate discovery populations from the pinned client-specific NPC catalogs.

Retail NPC/type counts match the raw TDB1210.26091 creature_template dump.
Forever counts cover ATT Camelot references only, not the entire game.
No catalog must be loaded in-game to select achievement thresholds.
"""
from collections import Counter
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
NPC = re.compile(r'D\.npcs\[(\d+)\]=\{("(?:[^"\\]|\\.)*"),(-?\d+),(-?\d+),')


def populations():
    result = {}
    for client, folder in (("retail", "MobLog_TrinityDB"), ("forever", "MobLog_ForeverDB")):
        records = {}
        for path in sorted((ROOT / folder).glob("npcs-*.lua")):
            for match in NPC.finditer(path.read_text(encoding="utf-8")):
                records[int(match[1])] = (int(match[3]), int(match[4]))
        types = Counter(kind for _, kind in records.values())
        counts = {"all": len(records), "rare": sum(rank in (2, 4) for rank, _ in records.values()),
                  "elite": sum(rank in (1, 2) for rank, _ in records.values())}
        counts.update({kind: types[kind] for kind in (1, 2, 3, 4, 5, 6, 7, 8, 9, 15)})
        result[client] = counts
    return result


def build():
    lines = ["-- SPDX-License-Identifier: GPL-2.0-or-later",
             "-- Generated by tools/trinity/build_discovery_limits.py; do not edit counts by hand.",
             "-- Retail: TDB1210.26091; Forever: pinned ATT Camelot references (incomplete).",
             "local _, ML = ...", "ML.DiscoveryPopulations = {"]
    for client, counts in populations().items():
        lines.append("    " + client + " = {")
        for key, count in counts.items():
            field = "[" + str(key) + "]" if isinstance(key, int) else key
            lines.append(f"        {field}={count},")
        lines.append("    },")
    lines.extend(["}", ""])
    (ROOT / "MobLog/DiscoveryLimits.lua").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    build()
